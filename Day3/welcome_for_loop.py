# ============================================
# FOR LOOP EXAMPLE: Welcome People from List
# ============================================
print("\n--- Welcoming People Using For Loop ---")
people = ["Alice", "Bob", "Charlie", "Diana", "Eve"]  # create a list of people

# for loop iterates through each person in the people list
for person in people:
    print(f"Welcome, {person}!")  # print welcome message for each person

print("All people have been welcomed!")  # message after loop completes
