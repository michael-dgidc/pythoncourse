# ============================================
# WHILE LOOP EXAMPLE: Count to 20
# ============================================
print("\n--- Counting to 20 Using While Loop ---")
count = 1  # initialize counter variable to 1

# while loop continues as long as count is less than or equal to 20
while count <= 90:
    print(f"Iteration {count}: Count is {count}")  # print current iteration and count value
    count = count + 1  # increment count by 1 each iteration (count += 1)

print("Loop finished! Reached count of 20")  # message after loop completes
    
